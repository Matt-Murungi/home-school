#!/usr/bin/env python3
"""Schema convention for the Appwrite tables (M01, #36). Stdlib only, offline.

Source of truth: one JSON file per domain in `schema/` (`_base.json`, `core.json`, later `catalogue.json`,
`scheduling.json`, ...). Each ticket adds or edits ITS OWN file, so schema tickets do not conflict.

Generated (never edit by hand; `--write` regenerates, `--check` fails when stale, tests and `make lint` run it):
- `appwrite.config.json` key `tables` = all domains in file-name order (`_base` first), `databaseId` injected.
  Other keys (buckets, functions, project) stay hand-edited in `appwrite.config.json`.
- `docs/erd/<domain>.md` = Mermaid ERD per domain (not for `_base`).

Domain file shape:
  {"domain": "core", "description": "...",
   "tables": [Appwrite CLI table objects without databaseId],
   "meta": {"<table>": {"deletion": "soft|history|immutable|join|hard", "note": "...", "non_fk": {"<id-like column>": "why"}}},
   "relations": [{"from": "table.column", "to": "table", "deferred": "why the target table is not here yet"}]}
Every `*_id`/`*_ids` column must be a relation (varchar(36), indexed, target exists or deferred) or be listed in
`meta[table].non_fk` with a reason (file ids): `validate()` enforces it for every domain.

Applying: a numbered migration calls `apply_domain(client, "core")` (see migrations/0002_core_schema.py); a later schema
change edits the domain file and adds a new migration that calls `apply_domain(client, "core", only=[...changed tables])`.
`ensure_table` only creates what is missing and fails on drift; it never alters or drops.

usage: schema_build.py [--check | --write]
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCHEMA_DIR = HERE / "schema"
CONFIG_PATH = HERE / "appwrite.config.json"
ERD_DIR = HERE.parent / "docs" / "erd"
DATABASE_ID = "main"

MAX_ROW_BYTES = 65535  # Appwrite/MariaDB row width limit (estimate below)
MAX_VARCHAR = 16383
MAX_INDEX_CHARS = 768  # sum of indexed varchar sizes (3072-byte index key limit / 4 bytes per char)
MAX_INDEXES = 64
TABLE_ID_RE = re.compile(r"^[a-z][a-z0-9_]{0,35}$")
KEY_RE = re.compile(r"^[a-z][a-z0-9_]{0,47}$")
ROLE_RE = re.compile(r"^[a-z0-9]+$")
TYPES = {"varchar", "text", "integer", "boolean", "datetime", "string"}  # string only with format enum
INDEX_TYPES = {"key", "unique", "fulltext"}
DELETION = {"soft", "history", "immutable", "join", "hard"}
MONEY_WORDS = re.compile(r"(amount|price|rate|fee|cost|balance|ugx|salary|payout)")
FORBIDDEN_PERMS = re.compile(r'^(create|update|delete|write)\(|\((\\?")?(any|users)(\\?")?\)')


# --- loading and generating ----------------------------------------------------------------------------------------
def load_domains(directory=None) -> list[dict]:
    paths = sorted(Path(directory or SCHEMA_DIR).glob("*.json"), key=lambda p: p.name)
    return [json.loads(p.read_text()) for p in paths]


def build_config(base: dict, domains: list[dict]) -> dict:
    out = dict(base)
    out["tables"] = [_with_database(t) for d in domains for t in d["tables"]]
    return out


def _with_database(table: dict) -> dict:
    t = {k: v for k, v in table.items() if k != "databaseId"}
    return {"$id": t.pop("$id"), "databaseId": DATABASE_ID, **t}


def dump(obj) -> str:
    return json.dumps(obj, indent=2) + "\n"


def expected_config(domains=None) -> str:
    domains = domains or load_domains()
    base = json.loads(CONFIG_PATH.read_text())
    return dump(build_config(base, domains))


def render_erd(domain: dict, all_tables: dict) -> str:
    lines = [
        f"<!-- GENERATED by appwrite/schema_build.py from appwrite/schema/{domain['domain']}.json. Do not edit; run `python3 appwrite/schema_build.py --write`. -->",
        f"# ERD: {domain['domain']}",
        "",
        domain.get("description", ""),
        "",
        "```mermaid",
        "erDiagram",
    ]
    rel_cols = {r["from"] for r in domain.get("relations", [])}
    for t in domain["tables"]:
        lines.append(f"  {t['$id']} {{")
        uniques = {c for i in t["indexes"] if i["type"] == "unique" and len(i["columns"]) == 1 for c in i["columns"]}
        for c in t["columns"]:
            typ = "enum" if c.get("format") == "enum" else c["type"]
            marks = []
            if f"{t['$id']}.{c['key']}" in rel_cols:
                marks.append("FK")
            if c["key"] in uniques:
                marks.append("UK")
            lines.append(f"    {typ} {c['key']}{' ' + ','.join(marks) if marks else ''}")
        lines.append("  }")
    deferred = []
    for r in domain.get("relations", []):
        table, column = r["from"].split(".")
        if "deferred" in r:
            deferred.append(r)
            continue
        t = next(x for x in domain["tables"] if x["$id"] == table)
        col = next(c for c in t["columns"] if c["key"] == column)
        one = any(i["type"] == "unique" and i["columns"] == [column] for i in t["indexes"])
        left = "||" if col["required"] else "|o"
        right = "o|" if one else "o{"
        lines.append(f'  {r["to"]} {left}--{right} {table} : "{column}"')
    lines += ["```", "", "## Tables", ""]
    for t in domain["tables"]:
        m = domain["meta"][t["$id"]]
        lines.append(f"- `{t['$id']}` ({m['deletion']}): {m.get('note', '')}")
    if deferred:
        lines += ["", "## Relations to tables that arrive in later tickets", ""]
        lines += [f"- `{r['from']}` -> `{r['to']}`: {r['deferred']}" for r in deferred]
    return "\n".join(lines) + "\n"


def erd_texts(domains=None) -> dict[str, str]:
    domains = domains or load_domains()
    tables = {t["$id"]: t for d in domains for t in d["tables"]}
    return {d["domain"]: render_erd(d, tables) for d in domains if d["domain"] != "base"}


def check(config_text: str | None = None, domains=None) -> list[str]:
    domains = domains or load_domains()
    errors = validate(domains)
    current = config_text if config_text is not None else CONFIG_PATH.read_text()
    if current != expected_config(domains):
        errors.append("appwrite.config.json is not up to date with appwrite/schema/*.json (run schema_build.py --write)")
    return errors


def check_erd(texts: dict[str, str] | None = None, domains=None) -> list[str]:
    errors = []
    for name, want in erd_texts(domains).items():
        path = ERD_DIR / f"{name}.md"
        have = (texts or {}).get(name) if texts is not None else (path.read_text() if path.exists() else None)
        if have != want:
            errors.append(f"docs/erd/{name}.md is not up to date (run schema_build.py --write)")
    return errors


# --- validation ----------------------------------------------------------------------------------------------------
def row_width(table: dict) -> int:
    """Estimated bytes per row (utf8mb4: 4 bytes per varchar char; text and arrays are stored off-row)."""
    total = 0
    for c in table["columns"]:
        if c.get("array") or c["type"] == "text":
            total += 12
        elif c["type"] == "varchar":
            total += 4 * c["size"] + 2
        elif c.get("format") == "enum":
            total += 4 * max(len(e) for e in c["elements"]) + 2
        elif c["type"] in ("integer", "datetime"):
            total += 8
        else:
            total += 1
    return total


def validate(domains: list[dict]) -> list[str]:
    errors: list[str] = []
    all_tables: dict[str, dict] = {}
    for d in domains:
        for t in d["tables"]:
            if t["$id"] in all_tables:
                errors.append(f"duplicate table {t['$id']} (domain {d['domain']})")
            all_tables[t["$id"]] = t
    for d in domains:
        meta = d.get("meta", {})
        for t in d["tables"]:
            errors += _validate_table(t, meta.get(t["$id"]))
        for r in d.get("relations", []):
            errors += _validate_relation(r, all_tables)
        errors += _validate_fk_like_columns(d)
    return errors


def _validate_fk_like_columns(d: dict) -> list[str]:
    """Every `*_id` / `*_ids` column is a declared relation (so its FK rules and index are enforced) or is listed in
    `meta[table].non_fk` with a reason (e.g. an Appwrite Storage file id). Applies to every domain file."""
    e, declared = [], {r["from"] for r in d.get("relations", [])}
    for t in d["tables"]:
        tid = t["$id"]
        non_fk = (d.get("meta", {}).get(tid) or {}).get("non_fk", {})
        keys = {c["key"] for c in t["columns"]}
        for k in non_fk:
            if k not in keys:
                e.append(f"{tid}: meta.non_fk lists unknown column {k}")
            elif f"{tid}.{k}" in declared:
                e.append(f"{tid}.{k}: listed in non_fk but also declared as a relation")
        for k in sorted(keys):
            if (k.endswith("_id") or k.endswith("_ids")) and f"{tid}.{k}" not in declared and k not in non_fk:
                e.append(f"{tid}.{k}: id-like column must be a declared relation (with an FK index) or listed in meta.non_fk with a reason")
    return e


def _validate_table(t: dict, meta: dict | None) -> list[str]:
    tid = t["$id"]
    e: list[str] = []
    if not TABLE_ID_RE.match(tid):
        e.append(f"{tid}: bad table id")
    if t.get("rowSecurity") is not True:
        e.append(f"{tid}: rowSecurity must be true")
    perms = t.get("$permissions", None)
    if perms != []:
        e.append(f"{tid}: table-level permissions must be empty (ADR 0012); got {perms!r}")
    for p in perms or []:
        if FORBIDDEN_PERMS.search(p):
            e.append(f"{tid}: forbidden permission {p}")
    if not t.get("columns"):
        e.append(f"{tid}: no columns")
    keys: dict[str, dict] = {}
    for c in t.get("columns", []):
        k = c.get("key", "")
        if k in keys:
            e.append(f"{tid}.{k}: duplicate column")
        keys[k] = c
        e += _validate_column(tid, c)
    if sum(1 for _ in keys) and row_width(t) > MAX_ROW_BYTES:
        e.append(f"{tid}: estimated row width {row_width(t)} exceeds {MAX_ROW_BYTES} bytes")
    e += _validate_indexes(t, keys)
    # deletion policy (SR 5.5)
    deletion = (meta or {}).get("deletion")
    if deletion not in DELETION:
        e.append(f"{tid}: meta.deletion must be one of {sorted(DELETION)}")
    elif deletion == "soft":
        c = keys.get("deleted_at")
        if not c or c["type"] != "datetime" or c["required"]:
            e.append(f"{tid}: soft-delete tables need an optional datetime deleted_at")
    elif deletion == "immutable":
        bad = [k for k in ("deleted_at", "revoked_at", "updated_at") if k in keys]
        if bad:
            e.append(f"{tid}: immutable (insert-only) table must not have {bad}")
    elif deletion == "history" and "revoked_at" not in keys:
        e.append(f"{tid}: history tables need revoked_at")
    return e


def _validate_column(tid: str, c: dict) -> list[str]:
    k, e = c.get("key", "?"), []
    where = f"{tid}.{k}"
    if not KEY_RE.match(k):
        e.append(f"{where}: bad column key")
    t = c.get("type")
    if t not in TYPES:
        e.append(f"{where}: unsupported type {t!r} (floats are not allowed; money is integer UGX)")
        return e
    if not isinstance(c.get("required"), bool):
        e.append(f"{where}: required must be a boolean")
    if c.get("required") and "default" in c:
        e.append(f"{where}: a required column cannot have a default (Appwrite)")
    if t == "varchar" and not (isinstance(c.get("size"), int) and 1 <= c["size"] <= MAX_VARCHAR):
        e.append(f"{where}: varchar size must be 1..{MAX_VARCHAR}")
    if t == "string":
        if c.get("format") != "enum" or not c.get("elements"):
            e.append(f"{where}: type string is only used for enums (format enum + elements)")
        else:
            if "default" in c and c["default"] not in c["elements"]:
                e.append(f"{where}: default is not an enum element")
            if k == "role":
                for r in c["elements"]:
                    if not ROLE_RE.match(r):
                        e.append(f"{where}: role label {r!r} must be lower-case alphanumeric (ADR 0012)")
    if t == "datetime" and not k.endswith("_at"):
        e.append(f"{where}: datetime columns end in _at (UTC instants)")
    if k.endswith("_at") and t != "datetime":
        e.append(f"{where}: columns ending _at must be datetime (UTC)")
    if (k.endswith("_date") or k == "date_of_birth") and not (t == "varchar" and c.get("size") == 10):
        e.append(f"{where}: calendar dates are ISO strings varchar(10)")
    if re.search(r"(^|_)(lat|lng)(_|$)", k) and t != "integer":
        e.append(f"{where}: coordinates are integer micro-degrees (no floats)")
    if MONEY_WORDS.search(k) and t != "integer":
        e.append(f"{where}: money columns must be integer UGX")
    return e


def _validate_indexes(t: dict, keys: dict[str, dict]) -> list[str]:
    tid, e, names = t["$id"], [], set()
    if len(t.get("indexes", [])) > MAX_INDEXES:
        e.append(f"{tid}: more than {MAX_INDEXES} indexes")
    for i in t.get("indexes", []):
        where = f"{tid}.{i.get('key')}"
        if i.get("key") in names:
            e.append(f"{where}: duplicate index key")
        names.add(i.get("key"))
        if i.get("type") not in INDEX_TYPES:
            e.append(f"{where}: bad index type")
        cols = i.get("columns", [])
        if not cols:
            e.append(f"{where}: no columns")
        if len(i.get("orders", [])) != len(cols):
            e.append(f"{where}: orders must match columns")
        size, arrays = 0, 0
        for c in cols:
            if c not in keys:
                e.append(f"{where}: unknown column {c}")
                continue
            if keys[c]["type"] == "text" and i.get("type") != "fulltext":
                e.append(f"{where}: text column {c} cannot be indexed")
            size += keys[c].get("size", 0)
            arrays += 1 if keys[c].get("array") else 0
        if size > MAX_INDEX_CHARS:
            e.append(f"{where}: indexed varchar size {size} exceeds {MAX_INDEX_CHARS}")
        if arrays > 1:
            e.append(f"{where}: only one array column per index")
    return e


def _validate_relation(r: dict, all_tables: dict[str, dict]) -> list[str]:
    e = []
    table, _, column = r["from"].partition(".")
    t = all_tables.get(table)
    if not t:
        return [f"relation {r['from']}: unknown table {table}"]
    col = next((c for c in t["columns"] if c["key"] == column), None)
    if not col:
        return [f"relation {r['from']}: unknown column"]
    if not (col["type"] == "varchar" and col.get("size") == 36):
        e.append(f"relation {r['from']}: foreign keys are varchar(36)")
    if not any(i["columns"][0] == column for i in t["indexes"]):
        e.append(f"relation {r['from']}: foreign key has no index starting with it")
    if "deferred" not in r and r["to"] not in all_tables:
        e.append(f"relation {r['from']}: target table {r['to']} does not exist")
    return e


# --- applying ------------------------------------------------------------------------------------------------------
def apply_domain(client, domain: str, only=None, directory=None) -> list[dict]:
    """Create the domain's tables (or only the named ones) through the migration client. Idempotent."""
    found = next((d for d in load_domains(directory) if d["domain"] == domain), None)
    if not found:
        raise ValueError(f"unknown schema domain {domain!r}")
    results = []
    for t in found["tables"]:
        if only is None or t["$id"] in only:
            results.append(client.ensure_table(t))
    return results


def main(argv=None, out=sys.stdout) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--check", action="store_true", help="validate and fail if generated files are stale (default)")
    g.add_argument("--write", action="store_true", help="validate, then regenerate appwrite.config.json and docs/erd")
    args = ap.parse_args(argv)
    domains = load_domains()
    errors = validate(domains)
    if errors:
        print("\n".join(f"ERROR: {x}" for x in errors), file=out)
        return 1
    if args.write:
        CONFIG_PATH.write_text(expected_config(domains))
        ERD_DIR.mkdir(parents=True, exist_ok=True)
        for name, text in erd_texts(domains).items():
            (ERD_DIR / f"{name}.md").write_text(text)
        print("wrote appwrite.config.json and docs/erd/*.md", file=out)
        return 0
    stale = check_config_only(domains) + check_erd(domains=domains)
    print("\n".join(f"ERROR: {x}" for x in stale) or f"schema ok ({sum(len(d['tables']) for d in domains)} tables)", file=out)
    return 1 if stale else 0


def check_config_only(domains) -> list[str]:
    return [] if CONFIG_PATH.read_text() == expected_config(domains) else ["appwrite.config.json is not up to date (run schema_build.py --write)"]


if __name__ == "__main__":
    sys.exit(main())
