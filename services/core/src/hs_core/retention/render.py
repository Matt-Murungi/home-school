"""Renders the policy to docs/legal/retention-schedule.md (the lawyer reviews that file).

python -m hs_core.retention.render            # write
python -m hs_core.retention.render --check    # exit 1 when the file is stale (also a test)
"""

from __future__ import annotations

import sys
from pathlib import Path

from .policy import POLICY, SOFT_TABLES, Action, Rule, purge_order

OUT = Path(__file__).resolve().parents[5] / "docs" / "legal" / "retention-schedule.md"

CLASS_TITLES = {
    "account": "Accounts and contact data",
    "child_record": "Child records (children, logs, uploads, assessments)",
    "teacher_record": "Teacher records (profile, documents, availability)",
    "session_ops": "Subscriptions, matching and sessions",
    "money": "Money (payments, invoices, earnings, payouts, ledger)",
    "safeguarding": "Safeguarding",
    "consent": "Consent and requests (proof)",
    "audit": "Audit log",
    "notification": "Notifications",
    "reference": "Reference data (no personal data)",
    "operational": "Operational data",
}
ACTION_TEXT = {
    Action.HARD_DELETE: "delete",
    Action.ANONYMISE: "anonymise",
    Action.KEEP: "keep",
    Action.CASCADE: "with parent",
}


def _period(r: Rule) -> str:
    if r.period is None:
        return "no age rule"
    text = r.period.human
    return f"{text} (placeholder)" if r.pending else text


def _clock(r: Rule) -> str:
    if r.clock is None:
        return "-"
    return "last subscription end / `deleted_at`" if r.table == "child" else f"`{r.clock}`"


def _row(r: Rule) -> str:
    floor = r.floor.human if r.floor else "-"
    subjects = (
        ", ".join(sorted({*r.subjects.values(), *([r.own_subject] if r.own_subject else [])}))
        or "-"
    )
    extra = []
    if r.files:
        extra.append("files: " + ", ".join(f"{f.bucket}" for f in r.files))
    if r.where:
        extra.append("only " + ", ".join(f"{k} in ({'/'.join(v)})" for k, v in r.where.items()))
    if r.payload_expiry:
        extra.append(f"variables stripped after {r.payload_expiry.human}")
    if r.never_purge:
        extra.append("NEVER purged by code")
    if r.append_only:
        extra.append("append-only")
    if r.table in SOFT_TABLES and r.action is Action.HARD_DELETE:
        extra.append("quarantined (soft delete) first")
    if r.enforced_by != "retention-purge":
        extra.append(f"enforced by `{r.enforced_by}`")
    note = " ".join(x for x in [r.note, *(f"({e})" for e in extra)] if x)
    return (
        f"| `{r.table}` | {r.basis.value} | {ACTION_TEXT[r.action]} | {_period(r)} | {floor} | "
        f"{_clock(r)} | {subjects} | {r.dsr.value} | {note.replace('|', '/')} |"
    )


def render(policy: dict[str, Rule] | None = None) -> str:
    pol = policy or POLICY
    order = {t: i for i, t in enumerate(purge_order(pol))}
    lines = [
        "# Retention schedule (generated)",
        "",
        "<!-- GENERATED by `python -m hs_core.retention.render` from "
        "services/core/src/hs_core/retention/policy.py. "
        "Do not edit by hand: edit the policy and regenerate. A test fails when this file is stale. -->",
        "",
        "**Status: DRAFT for the lawyer (brief Q4, Q16, Q17, Q23-Q26). Every period marked "
        '"placeholder" is a conservative default (kept LONGER than likely needed) and has NOT been '
        "confirmed.** The purge job only reports what it would do (dry run) until the owner enables "
        "`RETENTION_ENFORCE`. Mechanism, settings and safeguards: `docs/legal/retention.md` and "
        "`docs/ops/retention.md`.",
        "",
        "How to read it: a row is **due** when today's Africa/Kampala date is after "
        "(Kampala date of the clock + the period); it is kept through the whole last day. "
        "Month and year steps that land on a day that does not exist roll forward (kept one day "
        "longer). **Floor** is the legal minimum the code enforces: a configured period shorter "
        "than the floor is refused at startup. **On deletion request** is what a data-subject "
        "deletion does (DP-5): `delete`, `anonymise` (personal fields replaced, amounts kept), "
        "`retain` (kept: legal basis or proof) or `none`.",
        "",
    ]
    by_class: dict[str, list[Rule]] = {}
    for r in pol.values():
        by_class.setdefault(r.data_class, []).append(r)
    head = (
        "| Table | Basis | At expiry | Period | Floor | Clock | Subject | On deletion request | Notes |\n"
        "|---|---|---|---|---|---|---|---|---|"
    )
    for cls, title in CLASS_TITLES.items():
        rules = sorted(by_class.pop(cls, []), key=lambda r: order.get(r.table, 0))
        if not rules:
            continue
        lines += [f"## {title}", "", head, *(_row(r) for r in rules), ""]
    assert not by_class, f"data class without a title: {sorted(by_class)}"
    lines += [
        "## Order of purging",
        "",
        "Children before parents (references are restricted, cascaded or replaced by a pseudonym): "
        + ", ".join(f"`{t}`" for t in purge_order(pol))
        + ".",
        "",
        "## Holds",
        "",
        "A legal hold (`retention_hold`: child, parent, teacher, user, safeguarding case or one row) "
        "stops any purge or anonymisation of the subject's rows. An open safeguarding case holds its "
        "child and its teacher automatically. Rows inherit the holds of the rows they reference.",
        "",
    ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    args = argv if argv is not None else sys.argv[1:]
    text = render()
    if "--check" in args:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale: run `python -m hs_core.retention.render`")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
