"""THE retention policy (C03 #141, SR DP-6): one declarative rule per schema table.

Every default period here is a PLACEHOLDER pending the lawyer's confirmation (docs/legal/
lawyer-brief.md Q4, Q16, Q17, Q23-Q26) and is deliberately on the LONG side: a period that is too
long is corrected by a setting; a record deleted too early cannot be brought back. SR DP-6 names
the data classes but states no numbers. Periods are configurable (`RETENTION_PERIODS`, a JSON
object table -> '90d' | '18m' | '7y'); a setting may lengthen a period but never shorten it below
the rule's FLOOR (the legal minimum, e.g. tax records), see `effective_periods`.

What a rule says (the rendered table is docs/legal/retention-schedule.md, generated by
`python -m hs_core.retention.render`, drift-tested; the lawyer reviews that file):

- `action`: HARD_DELETE (row and its files go), ANONYMISE (personal fields are replaced by
  tombstones, amounts and ids stay: payments, invoices), KEEP (never purged by age: reference data,
  proof of consent, ledger, audit log) or CASCADE (goes with its parent row, never by its own age).
- `clock`: the column the period counts from; `None` = no age rule (KEEP/CASCADE). The child's
  effective clock is the LATER of its `deleted_at` and the end of its last subscription (retention
  "after cancellation", `clocks.child_clock`), and a child with a live subscription is never due.
- `links`: references to parent rows and what happens when the parent is purged (RESTRICT: the
  parent is not purged while such rows exist; CASCADE: they go first; ANONYMISE: the reference is
  replaced by a tombstone, the row stays; IGNORE: a dangling pseudonymous id is acceptable). This is
  also the delete ORDER: children before parents (`purge_order`).
- `subjects`: the columns that tie a row to a data subject (hold and deletion-request lookups).
- `dsr`: what a data-subject deletion request does to rows of the subject (DP-5).
- `files`: Storage objects owned by the row; deleted BEFORE the row.

`append_only` tables (ledger, audit log, safeguarding actions) are never purged by the normal path.
"""

