POLICY: dict[str, Rule] = {r.table: r for r in _RULES}
assert len(POLICY) == len(_RULES), "duplicate rule"


class PolicyError(ValueError):
    pass


def purge_order(policy: dict[str, Rule] | None = None) -> list[str]:
    """Tables in the order they are purged: a table comes AFTER every table that references it
    with RESTRICT or CASCADE (children before parents)."""
    pol = policy or POLICY
    before: dict[str, set[str]] = {t: set() for t in pol}  # table -> tables that must go first
    for r in pol.values():
        for ln in r.links:
            if (
                ln.on_parent_purge in (OnParentPurge.RESTRICT, OnParentPurge.CASCADE)
                and ln.parent in pol
            ):
                before[ln.parent].add(r.table)
    out: list[str] = []
    seen: set[str] = set()
    visiting: set[str] = set()

    def visit(t: str) -> None:
        if t in seen:
            return
        if t in visiting:
            raise PolicyError(f"cycle in retention links at {t}")
        visiting.add(t)
        for c in sorted(before[t]):
            visit(c)
        visiting.discard(t)
        seen.add(t)
        out.append(t)

    for t in sorted(pol):
        visit(t)
    return out


def referencing(table: str, policy: dict[str, Rule] | None = None) -> list[tuple[Rule, Link]]:
    """Rows of which tables point at `table` (for the restrict/cascade/anonymise handling)."""
    pol = policy or POLICY
    return [(r, ln) for r in pol.values() for ln in r.links if ln.parent == table]


def parse_overrides(text: str) -> dict[str, Period]:
    if not text.strip():
        return {}
    try:
        raw = json.loads(text)
    except ValueError:
        raise PolicyError("RETENTION_PERIODS is not valid JSON") from None
    if not isinstance(raw, dict):
        raise PolicyError("RETENTION_PERIODS must be a JSON object")
    out = {}
    for table, value in raw.items():
        try:
            out[str(table)] = Period.parse(value)
        except PeriodError as e:
            raise PolicyError(f"RETENTION_PERIODS[{table}]: {e}") from None
    return out


def effective_policy(overrides: dict[str, Period] | None = None) -> dict[str, Rule]:
    """The policy with configured periods applied. A period shorter than the rule's floor, an
    override for an unknown table or for a rule without a period is a configuration ERROR (it
    would otherwise silently weaken a legal minimum or do nothing)."""
    out = dict(POLICY)
    for table, period in (overrides or {}).items():
        rule = POLICY.get(table)
        if rule is None:
            raise PolicyError(f"RETENTION_PERIODS names unknown table {table}")
        if rule.period is None or rule.never_purge:
            raise PolicyError(f"RETENTION_PERIODS: {table} has no age rule to configure")
        if rule.floor is not None and period.shorter_than(rule.floor):
            raise PolicyError(
                f"RETENTION_PERIODS[{table}]={period} is shorter than the legal floor {rule.floor}"
            )
        out[table] = replace(rule, period=period)
    return out


def undecided_tables(
    schema_tables: set[str] | frozenset[str], policy: dict[str, Rule] | None = None
) -> list[str]:
    """Schema tables with no retention decision. The coverage test (and CI through it) fails when
    this is not empty: a new table cannot merge without saying how long its rows live."""
    return sorted(set(schema_tables) - set(policy or POLICY))


def unknown_rule_tables(
    schema_tables: set[str] | frozenset[str], policy: dict[str, Rule] | None = None
) -> list[str]:
    """Rules for tables that do not exist (typos, dropped tables)."""
    return sorted(set(policy or POLICY) - set(schema_tables))
