PSEUDO = "@pseudonym"  # tombstone: a stable one-way pseudonym of the original value
NULL = None


class Action(StrEnum):
    HARD_DELETE = "hard_delete"
    ANONYMISE = "anonymise"
    KEEP = "keep"
    CASCADE = "cascade"


class Basis(StrEnum):
    LEGAL = "legal"  # a statute or a regulator sets (a minimum of) the period
    OPERATIONAL = "operational"  # we need it to run the service; shorter is better
    PROOF = "proof"  # kept as evidence (consent, requests, audit)


class OnParentPurge(StrEnum):
    RESTRICT = "restrict"
    CASCADE = "cascade"
    ANONYMISE = "anonymise"
    IGNORE = "ignore"


class Dsr(StrEnum):
    DELETE = "delete"
    ANONYMISE = "anonymise"
    RETAIN = "retain"  # kept (legal basis) with personal fields minimised where the rule says so
    NONE = "none"  # the table holds nothing about a data subject


@dataclass(frozen=True)
class Link:
    column: str  # column of THIS table
    parent: str  # table it references
    on_parent_purge: OnParentPurge = OnParentPurge.RESTRICT
    inherit_hold: bool = True  # a hold on the parent row also holds this row


@dataclass(frozen=True)
class FileRef:
    bucket: str
    column: str


@dataclass(frozen=True)
class Rule:
    table: str
    data_class: str
    basis: Basis
    action: Action
    period: Period | None = None
    floor: Period | None = None
    clock: str | None = None
    where: dict[str, tuple[str, ...]] = field(default_factory=dict)  # equal() prefilter
    links: tuple[Link, ...] = ()
    subjects: dict[str, str] = field(
        default_factory=dict
    )  # column -> child|parent|teacher|user|case
    own_subject: str | None = None  # this table's rows ARE subjects of this kind
    anonymise: dict[str, dict[str, Any]] = field(
        default_factory=dict
    )  # subject kind|'*' -> col -> tombstone
    marker: tuple[str, str] | None = None  # (column, prefix) every anonymised row carries
    files: tuple[FileRef, ...] = ()
    dsr: Dsr = Dsr.NONE
    never_purge: bool = False  # code refuses any purge (ledger)
    enforced_by: str = "retention-purge"
    pending: bool = True  # period awaits the lawyer
    payload_expiry: Period | None = None  # N01 notification payloads: variables stripped earlier
    note: str = ""

    @property
    def append_only(self) -> bool:
        return self.table in APPEND_ONLY


